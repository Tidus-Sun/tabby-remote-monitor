export function resolveLanguage (preference: LanguagePreference, hostLocale?: string): Language {
    if (preference !== 'auto') return preference
    const locale = (hostLocale || (typeof navigator !== 'undefined' ? navigator.language : 'en')).replace(/_/g, '-').toLowerCase()
    return locale === 'zh' || locale === 'zh-cn' || locale === 'zh-sg' || locale.startsWith('zh-hans') ? 'zh-CN' : 'en'
}

export function translate (language: Language, key: MessageKey, params: TranslationParams = {}): string {
    const message = (language === 'zh-CN' ? zhCN[key] : en[key]) ?? en[key]
    // Parameter values remain literal text, including any braces or HTML in host names.
    return message.replace(/\{(\w+)\}/g, (match, name: string) => Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match)
}

export class LocalizedError extends Error {
    constructor (readonly key: MessageKey, readonly params: TranslationParams = {}) { super(translate('zh-CN', key, params)) }
}
